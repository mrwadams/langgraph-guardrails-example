"""
Example 6: Production-Ready Multi-Guardrail System
===================================================

This example demonstrates a production-ready setup with:
- Multi-layer input validation
- Optional LLM-based content safety (Claude 4.5 Haiku)
- Agent processing with tool calls
- Output validation
- Error handling
- Metrics tracking
- Configurable safety levels

This is close to what you'd deploy in a real production system.

Setup:
- For basic guardrails: Works out of the box
- For LLM-based safety: Add ANTHROPIC_API_KEY to .env file
"""

from typing import TypedDict, Literal
from langgraph.graph import StateGraph, END
from guardrails.base import GuardrailChain
from guardrails.input_guardrails import (
    InputLengthGuardrail,
    TopicValidationGuardrail,
    RateLimitGuardrail,
)
from guardrails.safety_guardrails import (
    PIIDetectionGuardrail,
    PromptInjectionGuardrail,
    ContentSafetyGuardrail,
)
from guardrails.output_guardrails import OutputLengthGuardrail
from guardrails.config import create_anthropic_llm, get_anthropic_api_key


# Define the state
class ProductionAgentState(TypedDict):
    # User input
    input: str
    user_id: str
    metadata: dict

    # Messages
    messages: list

    # Guardrail results (many fields)
    InputLength_result: str
    TopicValidation_result: str
    RateLimit_result: str
    PIIDetection_result: str
    PromptInjection_result: str
    ContentSafety_result: str
    OutputLength_result: str

    # Agent state
    processing_error: bool
    rejected: bool


# Configuration
class SafetyLevel:
    STRICT = "strict"
    MODERATE = "moderate"
    PERMISSIVE = "permissive"


def create_input_guardrails(safety_level: str = SafetyLevel.MODERATE, use_llm_safety: bool = True):
    """
    Create input guardrails based on safety level.

    Args:
        safety_level: Security strictness level
        use_llm_safety: If True and API key available, use Claude 4.5 Haiku for content safety
    """

    if safety_level == SafetyLevel.STRICT:
        max_length = 500
        rate_limit_per_min = 5
        rate_limit_per_hour = 50
    elif safety_level == SafetyLevel.PERMISSIVE:
        max_length = 2000
        rate_limit_per_min = 20
        rate_limit_per_hour = 200
    else:  # MODERATE
        max_length = 1000
        rate_limit_per_min = 10
        rate_limit_per_hour = 100

    guardrails = [
        # Layer 1: Fast, cheap checks
        InputLengthGuardrail(
            min_length=3,
            max_length=max_length,
            truncate=False,
        ),
        RateLimitGuardrail(
            max_requests_per_minute=rate_limit_per_min,
            max_requests_per_hour=rate_limit_per_hour,
        ),

        # Layer 2: Security checks
        PromptInjectionGuardrail(strict=True),

        # Layer 3: Content validation
        TopicValidationGuardrail(
            allowed_topics=["technology", "programming", "software", "AI", "machine learning"],
            fuzzy_match=True,
        ),

        # Layer 4: Privacy protection
        PIIDetectionGuardrail(
            redact=True,
            strict=False,
        ),
    ]

    # Layer 5: LLM-based content safety (optional, requires API key)
    if use_llm_safety and get_anthropic_api_key():
        try:
            llm = create_anthropic_llm()
            guardrails.append(
                ContentSafetyGuardrail(
                    llm=llm,
                    safety_categories=["violence", "hate", "sexual", "self-harm", "illegal"],
                    threshold=0.7,
                )
            )
            print("✓ Using Claude 4.5 Haiku for LLM-based content safety\n")
        except Exception as e:
            print(f"⚠ Could not initialize LLM safety guardrail: {e}\n")

    return GuardrailChain(guardrails)


def create_output_guardrails():
    """Create output validation guardrails"""
    return OutputLengthGuardrail(
        min_length=10,
        max_length=1000,
        truncate=True,
    )


# Create guardrails
input_guardrails = create_input_guardrails(SafetyLevel.MODERATE)
output_guardrails = create_output_guardrails()


# Agent node (simulated)
def agent_node(state: ProductionAgentState) -> ProductionAgentState:
    """Main agent processing node"""
    try:
        user_input = state["input"]

        # Simulate agent processing
        # In production, this would call your LLM with tools
        response = (
            f"I understand you're asking about '{user_input}'. "
            f"Here's a helpful response about this technology topic. "
            f"This would be generated by your actual LLM in production."
        )

        return {
            **state,
            "messages": [
                {"role": "user", "content": user_input},
                {"role": "assistant", "content": response},
            ],
            "processing_error": False,
        }
    except Exception as e:
        return {
            **state,
            "messages": [
                {"role": "user", "content": state["input"]},
                {
                    "role": "assistant",
                    "content": "I apologize, but I encountered an error processing your request.",
                },
            ],
            "processing_error": True,
        }


def error_handler_node(state: ProductionAgentState) -> ProductionAgentState:
    """Handle processing errors gracefully"""
    return {
        **state,
        "messages": [
            state["messages"][0] if state.get("messages") else {"role": "user", "content": ""},
            {
                "role": "assistant",
                "content": "I'm sorry, but I'm unable to process your request at this time. Please try again later.",
            },
        ],
    }


def route_output_validation(state: ProductionAgentState) -> str:
    """Route after output validation"""
    if state.get("processing_error"):
        return "error"

    result = state.get("OutputLength_result")
    if result == "block":
        return "error"

    return "success"


def build_production_agent():
    """Build production-ready agent with comprehensive guardrails"""
    workflow = StateGraph(ProductionAgentState)

    # Add nodes
    workflow.add_node("input_validation", input_guardrails.check)
    workflow.add_node("input_rejection", input_guardrails.rejection_node)
    workflow.add_node("agent", agent_node)
    workflow.add_node("output_validation", output_guardrails.check)
    workflow.add_node("error_handler", error_handler_node)

    # Set entry point
    workflow.set_entry_point("input_validation")

    # Input validation routing
    workflow.add_conditional_edges(
        "input_validation",
        input_guardrails.route,
        {
            "continue": "agent",
            "reject": "input_rejection",
        },
    )

    # Input rejection -> END
    workflow.add_edge("input_rejection", END)

    # Agent -> Output validation
    workflow.add_edge("agent", "output_validation")

    # Output validation routing
    workflow.add_conditional_edges(
        "output_validation",
        route_output_validation,
        {
            "success": END,
            "error": "error_handler",
        },
    )

    # Error handler -> END
    workflow.add_edge("error_handler", END)

    return workflow.compile()


def run_with_metrics(graph, test_cases):
    """Run test cases and collect metrics"""
    results = []

    for i, test_case in enumerate(test_cases, 1):
        print(f"\n{'='*60}")
        print(f"Test Case {i}: {test_case['description']}")
        print(f"{'='*60}")

        result = graph.invoke({
            "input": test_case["input"],
            "user_id": test_case.get("user_id", "test_user"),
            "metadata": test_case.get("metadata", {}),
        })

        print(f"Input: {test_case['input'][:100]}...")
        print(f"Rejected: {result.get('rejected', False)}")

        if result.get("rejected"):
            print(f"Reason: {result['messages'][-1]['content'][:200]}...")
        else:
            print(f"Response: {result['messages'][-1]['content'][:200]}...")

        # Show guardrail results
        print("\nGuardrail Results:")
        for key in result.keys():
            if key.endswith("_result"):
                print(f"  {key}: {result[key]}")

        results.append(result)

    return results


